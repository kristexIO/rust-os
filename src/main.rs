// =============================================================================
// Минимальное ядро ОС на Rust
// Архитектура: x86_64, вывод через VGA текстовый буфер
// =============================================================================

// Отключаем стандартную библиотеку Rust — она требует ОС (syscalls, аллокатор,
// поддержку потоков), которой у нас ещё нет.
#![no_std]

// Отключаем стандартную точку входа. Rust обычно генерирует код, который
// вызывает fn main(), но в нашем случае загрузчик вызывает _start напрямую.
#![no_main]

// =============================================================================
// ОБРАБОТЧИК ПАНИКИ
// =============================================================================

use core::panic::PanicInfo;

/// Эта функция вызывается при панике (аналог std::panic!).
/// Атрибут #[panic_handler] указывает компилятору использовать именно её.
/// Так как мы пока не умеем выводить информацию о панике, просто зависаем.
#[panic_handler]
fn panic(_info: &PanicInfo) -> ! {
    // Бесконечный цикл — CPU будет выполнять инструкцию `jmp` к самой себе,
    // полностью занимая одно ядро, но не давая выполниться ничему другому.
    // В будущем сюда можно добавить вывод информации об ошибке через VGA.
    loop {}
}

// =============================================================================
// VGA ТЕКСТОВЫЙ БУФЕР
// =============================================================================

/// Физический адрес начала VGA текстового буфера.
/// Этот адрес зафиксирован стандартом IBM PC и доступен в real mode и protected mode.
/// bootloader уже настроил таблицы страниц, сделав его доступным из ядра.
const VGA_BUFFER: *mut u16 = 0xb8000 as *mut u16;

/// Атрибут цвета: белый текст (0xF) на чёрном фоне (0x0).
/// Формат байта атрибута: [биты 7:4 — цвет фона] [биты 3:0 — цвет текста].
/// 0x0F = 0000_1111: фон = чёрный (0), текст = ярко-белый (15).
const COLOR_ATTR: u8 = 0x0F;

/// Записывает строку в VGA текстовый буфер, начиная с позиции (col, row).
///
/// # Параметры
/// - `text`: строка в кодировке ASCII (UTF-8 совместима для ASCII-символов)
/// - `col`: номер колонки (0–79 для стандартного 80-колоночного режима)
/// - `row`: номер строки (0–24 для стандартного 25-строчного режима)
///
/// # Безопасность
/// Функция использует `unsafe` для записи по сырому указателю на VGA-буфер.
/// Это необходимо, так как Rust не может проверить корректность доступа
/// к физической памяти на этапе компиляции. Мы знаем, что адрес 0xb8000
/// является валидным VGA-буфером на платформе x86_64 с PC-совместимым железом.
fn vga_print(text: &str, col: usize, row: usize) {
    // VGA буфер — это двумерный массив 25 строк × 80 символов.
    // Каждый элемент — 16-битное слово:
    //   [биты 15:8] — байт атрибута (цвет фона + цвет текста)
    //   [биты  7:0] — ASCII-код символа
    // Вычисляем линейный индекс первой позиции нашей строки.
    let start_offset = row * 80 + col;

    for (i, byte) in text.bytes().enumerate() {
        // Формируем 16-битное слово: атрибут в старшем байте, символ в младшем.
        let vga_char: u16 = (COLOR_ATTR as u16) << 8 | (byte as u16);

        // SAFETY: мы работаем с физической памятью VGA-буфера по известному
        // и всегда валидному адресу 0xb8000. Смещение ограничено шириной строки
        // (80 символов), поэтому выхода за пределы буфера (80×25 слов) нет.
        unsafe {
            // write_volatile гарантирует, что запись не будет оптимизирована
            // (выброшена) компилятором, даже если он решит, что результат
            // «никто не читает». Без volatile компилятор мог бы убрать эти записи.
            core::ptr::write_volatile(VGA_BUFFER.add(start_offset + i), vga_char);
        }
    }
}

// =============================================================================
// ТОЧКА ВХОДА ЯДРА
// =============================================================================

/// Точка входа, вызываемая загрузчиком (bootloader).
///
/// Атрибут `no_mangle` запрещает компилятору изменять имя функции (name mangling).
/// Это гарантирует, что компоновщик найдёт символ `_start` по его точному имени,
/// которое указано в linker script загрузчика.
///
/// `extern "C"` указывает использовать C calling convention (а не Rust ABI),
/// так как загрузчик написан на ассемблере/C и не знает о Rust ABI.
///
/// Возвращаемый тип `!` означает «никогда не возвращается» — ядро не имеет
/// куда возвращаться: нет вызывающей функции, нет стека ОС.
#[no_mangle]
pub extern "C" fn _start() -> ! {
    // Выводим приветственное сообщение в левый верхний угол экрана (строка 0, колонка 0).
    vga_print("Hello World!", 0, 0);

    // После вывода ядро уходит в бесконечный цикл ожидания.
    // В реальном ядре здесь был бы цикл планировщика задач или обработки прерываний.
    // Инструкция `hlt` усыпляет CPU до следующего прерывания, экономя энергию
    // (в отличие от полностью пустого цикла `loop {}`).
    loop {
        // SAFETY: инструкция `hlt` безопасна для вызова в привилегированном режиме (ring 0),
        // в котором работает ядро. Она просто переводит CPU в состояние низкого потребления
        // до ближайшего аппаратного прерывания, после чего выполнение продолжается.
        unsafe {
            core::arch::asm!("hlt", options(nomem, nostack, preserves_flags));
        }
    }
}
